insert into public.permission_modules (module_key, display_name, sort_order)
values ('invoice_requests', 'Invoice Requests', 85)
on conflict (module_key) do update set display_name = excluded.display_name,
  sort_order = excluded.sort_order, is_active = true, updated_at = now();

with actions(action_key, display_name, sort_order) as (values
  ('view', 'View', 10), ('create', 'Submit Request', 20),
  ('edit', 'Edit Request', 30), ('process', 'Process Request', 40),
  ('archive', 'Archive / Close', 50), ('reopen', 'Reopen', 60),
  ('delete', 'Delete', 70)
)
insert into public.permission_definitions (module_id, action_key, display_name, sort_order)
select pm.id, actions.action_key, actions.display_name, actions.sort_order
from actions cross join public.permission_modules pm
where pm.module_key = 'invoice_requests'
on conflict (module_id, action_key) do update set display_name = excluded.display_name,
  sort_order = excluded.sort_order, is_active = true, updated_at = now();

insert into public.role_default_permissions (role_key, permission_id, allowed)
select roles.role_key, pd.id, false
from (values ('admin'), ('sales'), ('accountant')) roles(role_key)
join public.permission_modules pm on pm.module_key = 'invoice_requests'
join public.permission_definitions pd on pd.module_id = pm.id
on conflict (role_key, permission_id) do nothing;

with allowed(role_key, action_key) as (values
  ('sales', 'view'), ('sales', 'create'), ('sales', 'edit'),
  ('accountant', 'view'), ('accountant', 'edit'), ('accountant', 'process'),
  ('accountant', 'archive'),
  ('admin', 'view'), ('admin', 'create'), ('admin', 'edit'), ('admin', 'process'),
  ('admin', 'archive'), ('admin', 'reopen'), ('admin', 'delete')
)
update public.role_default_permissions rdp set allowed = true, updated_at = now()
from public.permission_definitions pd
join public.permission_modules pm on pm.id = pd.module_id
join allowed a on a.action_key = pd.action_key
where pm.module_key = 'invoice_requests' and rdp.permission_id = pd.id
  and rdp.role_key = a.role_key;
